export function parseIndonesianCurrency(val: string | number | undefined): number {
  if (val === undefined || val === null || val === '') return 0;
  if (typeof val === 'number') return val;
  
  // Clean string
  let clean = val.replace(/Rp|\s|\./g, '').replace(/,/g, '.');
  let num = parseFloat(clean);
  if (isNaN(num)) return 0;

  // Real-world lab format check: e.g. "Rp400.00" in this sheet equals 400000 IDR
  // Notice that "Rp400.00" x 3 = "Rp1.200.000" (1200000).
  // If the raw text has ".00" at end and value is < 10000, multiply by 1000
  if (val.includes('.00') && !val.includes('.000') && num < 10000) {
    return num * 1000;
  }
  return num;
}

export function categorizeService(serviceName: string): { category: ServiceCategory; isMyAuthority: boolean } {
  const lower = (serviceName || '').toLowerCase();
  
  // Non-authority Walet services
  if (lower.includes('sarang burung walet') || lower.includes('walet')) {
    return { category: 'Pengujian Walet (Non-Authority)', isMyAuthority: false };
  }
  
  // User's specialized analytical services
  if (lower.includes('irms') || lower.includes('isotop')) {
    return { category: 'Isotop Rasio IRMS', isMyAuthority: true };
  }
  if (lower.includes('hplc') || lower.includes('gcms') || lower.includes('chromatography')) {
    return { category: 'Kromatografi (HPLC / GCMS)', isMyAuthority: true };
  }
  if (lower.includes('psa') || lower.includes('particle size') || lower.includes('icp-ms') || lower.includes('xrf') || lower.includes('flourosence') || lower.includes('zeta')) {
    return { category: 'Spektrometri & Partikel (PSA / ICP-MS / XRF)', isMyAuthority: true };
  }
  if (lower.includes('tga') || lower.includes('thermogravimetri') || lower.includes('chemisorption') || lower.includes('chemisorb') || lower.includes('autochem')) {
    return { category: 'Termal & Sorpsi (TGA / Chemisorption)', isMyAuthority: true };
  }
  if (lower.includes('ftir') || lower.includes('nmr') || lower.includes('bruker')) {
    return { category: 'Spektroskopi (FTIR / NMR)', isMyAuthority: true };
  }
  if (lower.includes('validasi') || lower.includes('karl fischer') || lower.includes('gliserol') || lower.includes('propanediol')) {
    return { category: 'Kimia Khusus & Validasi', isMyAuthority: true };
  }
  
  return { category: 'Lainnya', isMyAuthority: true };
}

// Convert "3 Agustus 2026" or "03/09/2026" to "2026-08-03"
export function parseIndonesianDateToIso(dateStr: string): string {
  if (!dateStr) return '2026-08-01';
  const str = dateStr.trim().toLowerCase();
  
  const monthMap: Record<string, string> = {
    'januari': '01', 'jan': '01',
    'februari': '02', 'feb': '02',
    'maret': '03', 'mar': '03',
    'april': '04', 'apr': '04',
    'mei': '05', 'may': '05',
    'juni': '06', 'jun': '06',
    'juli': '07', 'jul': '07',
    'agustus': '08', 'ags': '08', 'aug': '08',
    'september': '09', 'sep': '09',
    'oktober': '10', 'okt': '10', 'oct': '10',
    'november': '11', 'nov': '11',
    'desember': '12', 'des': '12', 'dec': '12',
  };

  for (const [mName, mNum] of Object.entries(monthMap)) {
    if (str.includes(mName)) {
      const parts = str.split(' ');
      const day = parts[0].padStart(2, '0');
      const year = parts[2] || '2026';
      return `${year}-${mNum}-${day}`;
    }
  }

  // Check if DD/MM/YYYY
  if (str.includes('/')) {
    const parts = str.split('/');
    if (parts.length === 3) {
      const day = parts[0].padStart(2, '0');
      const month = parts[1].padStart(2, '0');
      const year = parts[2].length === 2 ? `20${parts[2]}` : parts[2];
      return `${year}-${month}-${day}`;
    }
  }

  return '2026-08-01';
}

